"""Build six local WebP sheets from the pinned dashboard artwork."""
import argparse
import hashlib
import json
import math
import re
from pathlib import Path

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parent.parent


def resized(image, size):
    if image.ndim == 2:
        image = cv2.cvtColor(image, cv2.COLOR_GRAY2BGRA)
    elif image.shape[2] == 3:
        image = cv2.cvtColor(image, cv2.COLOR_BGR2BGRA)
    height, width = image.shape[:2]
    scale = size / max(width, height)
    target = (max(1, round(width * scale)), max(1, round(height * scale)))
    # Resize premultiplied alpha so transparent pixels cannot create dark fringes.
    rgba = image.astype(np.float32) / 255
    rgba[..., :3] *= rgba[..., 3:4]
    rgba = cv2.resize(rgba, target, interpolation=cv2.INTER_AREA if scale < 1 else cv2.INTER_CUBIC)
    rgba = np.clip(rgba, 0, 1)
    rgba[..., :3] = np.divide(rgba[..., :3], rgba[..., 3:4], out=np.zeros_like(rgba[..., :3]), where=rgba[..., 3:4] > 0)
    return np.clip(np.rint(rgba * 255), 0, 255).astype(np.uint8)


def artwork_groups(path):
    """Read the generated JSON constants without requiring Node for artwork refreshes."""
    text = path.read_text(encoding='utf-8')
    def constant(name):
        match = re.search(r'export const ' + name + r' = (.+);', text)
        if not match:
            raise ValueError(f'Missing generated artwork constant: {name}')
        return json.loads(match[1])
    icons, levels = constant('UPGRADE_ICONS'), constant('UPGRADE_LEVEL_ICONS')
    return {listing: sorted(set(entries.values()) | {
        image for versions in levels.get(listing, {}).values() for image in versions.values()})
        for listing, entries in icons.items()}


def build(source, destination, size=96, quality=90, module_path=None, groups=None):
    """One sheet per list. Shared artwork is duplicated so each list loads one image."""
    if not 1 <= size <= 512 or not 0 <= quality <= 101:
        raise ValueError('Invalid sprite size or quality')
    provenance = json.loads((source / 'sources.json').read_text(encoding='utf-8'))
    groups = groups if groups is not None else artwork_groups(ROOT / 'web/upgrade-icons.js')
    sources = set()
    for keys in groups.values():
        for key in keys:
            if not key.startswith('icons/entities/'):
                raise ValueError(f'Invalid artwork key: {key}')
            name = key.removeprefix('icons/entities/')
            if Path(name).name != name or name not in provenance['assets']:
                raise ValueError(f'Unpinned artwork: {key}')
            sources.add(name)
    destination.mkdir(parents=True, exist_ok=True)
    sheets, frames = {}, {}
    cell = size + 4
    for listing, entries in groups.items():
        entries = sorted(set(entries))
        if not entries or not re.fullmatch(r'[a-z_]+', listing):
            raise ValueError(f'Invalid or empty sprite group: {listing}')
        columns = math.ceil(math.sqrt(len(entries)))
        rows = math.ceil(len(entries) / columns)
        if max(columns, rows) * cell > 16383:
            raise ValueError('Sprite sheet exceeds WebP dimensions')
        sheet = np.zeros((rows * cell, columns * cell, 4), np.uint8)
        frames[listing] = {}
        for i, key in enumerate(entries):
            original = cv2.imread(str(source / key.removeprefix('icons/entities/')), cv2.IMREAD_UNCHANGED)
            if original is None:
                raise ValueError(f'Missing artwork: {key}')
            image = resized(original, size)
            x, y = i % columns * cell + 2, i // columns * cell + 2
            height, width = image.shape[:2]
            left, top = x + (size - width) // 2, y + (size - height) // 2
            sheet[top:top + height, left:left + width] = image
            frames[listing][key] = [x, y]
        ok, encoded = cv2.imencode('.webp', sheet, [cv2.IMWRITE_WEBP_QUALITY, quality])
        if not ok:
            raise ValueError('WebP encoding failed')
        payload = encoded.tobytes()
        filename = listing + '-' + hashlib.sha256(payload).hexdigest()[:12] + '.webp'
        (destination / filename).write_bytes(payload)
        sheets[listing] = [filename, sheet.shape[1], sheet.shape[0]]
    data = {'tile': size, 'sheets': sheets, 'sprites': frames, 'revision': provenance['revision']}
    if module_path is None:
        (destination / 'manifest.json').write_text(json.dumps(data, separators=(',', ':')) + '\n', encoding='utf-8')
    else:
        text = '// Generated by scripts/build_upgrade_sprites.py. Attribution: icons/entities/sources.json.\n'
        text += 'export const SPRITE_TILE = ' + str(size) + ';\n'
        text += 'export const SPRITE_SHEETS = ' + json.dumps(sheets, separators=(',', ':')) + ';\n'
        text += 'export const UPGRADE_SPRITES = ' + json.dumps(frames, separators=(',', ':')) + ';\n'
        temporary = module_path.with_suffix('.tmp')
        temporary.write_text(text, encoding='utf-8')
        temporary.replace(module_path)
    # Only this generated directory is cleaned, after every new sheet was written successfully.
    keep = {entry[0] for entry in sheets.values()}
    for old in destination.glob('*.webp'):
        if old.name not in keep:
            old.unlink()
    return {'tile': size, 'quality': quality, 'original_files': len(sources),
            'original_bytes': sum((source / name).stat().st_size for name in sources),
            'sprite_files': len(sheets), 'sprite_bytes': sum((destination / name).stat().st_size for name in keep),
            'mapping_bytes': module_path.stat().st_size if module_path else (destination / 'manifest.json').stat().st_size,
            'max_sheet_decoded_bytes': max(width * height * 4 for _, width, height in sheets.values())}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT / '.coc-auto/artwork/entities')
    parser.add_argument('--output', type=Path, default=ROOT / 'web/icons/sprites')
    parser.add_argument('--size', type=int, default=96)
    parser.add_argument('--quality', type=int, default=90)
    parser.add_argument('--module', type=Path, default=ROOT / 'web/upgrade-sprites.js')
    args = parser.parse_args()
    print(json.dumps(build(args.source, args.output, args.size, args.quality, args.module)))
