const STORE_LANG = 'coc-remote-lang';

function initialLanguage() {
  try {
    const saved = localStorage.getItem(STORE_LANG);
    if (saved in TEXT) return saved;
  } catch { /* storage unavailable */ }
  return (navigator.language || 'id').toLowerCase().startsWith('id') ? 'id' : 'en';
}

let language = initialLanguage();

/** @param {string} key @param {Record<string, string>} [params] @returns {string} */
export function t(key, params = {}) {
  const text = TEXT[language][key] ?? TEXT.id[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? '');
}

/** Fill every [data-i18n] element and [data-i18n-confirm] prompt in the page with the chosen language. */
export function applyLanguage(next = language) {
  language = next in TEXT ? next : 'id';
  try { localStorage.setItem(STORE_LANG, language); } catch { /* storage unavailable */ }
  document.documentElement.lang = language;
  for (const element of document.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
  for (const element of document.querySelectorAll('[data-i18n-confirm]')) element.dataset.confirm = t(element.dataset.i18nConfirm);
  for (const button of document.querySelectorAll('[data-lang]')) button.classList.toggle('active', button.dataset.lang === language);
}
